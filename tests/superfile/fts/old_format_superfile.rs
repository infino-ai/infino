//! A superfile written by the version-9 FTS writer answers every query
//! exactly as the same documents written by the current writer do.
//!
//! The fixture (`tests/fixtures/old_format_fts_superfile/`) was written
//! by the engine before version 10, over the corpus [`corpus`] generates.
//! Its corpus is shaped so that the file holds every block and group form
//! that writer produced, decoded here from real bytes rather than from
//! bytes the current encoder synthesizes:
//!
//! - long posting lists of thousands of documents, in packed, presence
//!   bitset and patched blocks, each storing its tfs as they are (header
//!   bit 31 clear), with tfs above one in each form;
//! - position groups of the packed form whose exceptions are varint
//!   pairs, with exceptions in both the first-position and the gap
//!   streams, and a short list's varint group;
//! - short-form lists and a single-document term.
//!
//! The test rebuilds the corpus with the current writer and asserts that
//! the old file answers term, conjunction, disjunction, required and
//! optional, negated and phrase queries with the same documents and
//! bit-identical scores, at every `k`, and that its unranked counts and
//! document frequencies are the same. Match sets are graded against
//! [`BruteForceBm25`] too, so both files are also held to an independent
//! answer. A merge of the old file alone is held to the same bar, which
//! reads every legacy block and group through the merge's postings walk.
//!
//! The fixture's README records how it was generated. The test asserts
//! its FTS section's version so the file cannot be regenerated by the
//! current writer without the test noticing.

use std::{
    collections::{HashMap, HashSet},
    path::Path,
    sync::Arc,
};

use bytes::Bytes;
use infino::{
    arrow_array::{Array, LargeStringArray, RecordBatch},
    arrow_schema::{DataType, Field, Schema},
    superfile::{
        SuperfileReader,
        builder::{BuilderOptions, FtsConfig, SuperfileBuilder},
        format::{fts, kv},
        fts::{reader::BoolMode, tokenize::Phrase},
    },
    test_helpers::{brute_force_bm25::BruteForceBm25, decimal128_ids, default_tokenizer},
};
use parquet::arrow::arrow_reader::ParquetRecordBatchReaderBuilder;

/// The version-9 superfile, relative to the crate root.
const FIXTURE: &str = "tests/fixtures/old_format_fts_superfile/v9.sf.parquet";

// The fixture grades a version older than the one the writer writes.
const _: () = assert!(fts::VERSION_CURRENT > fts::VERSION_V9);

/// The fixture's id and text columns.
const ID_COLUMN: &str = "doc_id";
const COLUMN: &str = "body";

/// Result depths every ranked query runs at: a single winner, a page, a
/// heap deeper than a block, past most lists, and every document.
const KS: [usize; 5] = [1, 10, 100, 1_000, N_DOCS as usize];

/// Every word the corpus holds, and one it does not, for the
/// document-frequency check.
const WORDS: [&str; 20] = [
    "common", "new", "york", "city", "music", "band", "album", "river", "quartz", "triad", "stone",
    "patch", "lynx", "onyx", "zephyr", "solo", "duo", "most", "every", "absent",
];

/// Ranked queries, in the query syntax, with the default operator each
/// runs under.
const QUERIES: [(&str, BoolMode); 36] = [
    // One term per list form: bitset, packed and bitset, patched, short,
    // single-document, and a word the corpus lacks.
    ("common", BoolMode::Or),
    ("every", BoolMode::Or),
    ("most", BoolMode::Or),
    ("triad", BoolMode::Or),
    ("patch", BoolMode::Or),
    ("quartz", BoolMode::Or),
    ("stone", BoolMode::Or),
    ("lynx", BoolMode::Or),
    ("duo", BoolMode::Or),
    ("solo", BoolMode::Or),
    ("absent", BoolMode::Or),
    // Disjunctions.
    ("common lynx", BoolMode::Or),
    ("triad patch", BoolMode::Or),
    ("every onyx zephyr", BoolMode::Or),
    ("most music album river", BoolMode::Or),
    // Conjunctions.
    ("every most", BoolMode::And),
    ("triad patch", BoolMode::And),
    ("common music band", BoolMode::And),
    ("every triad most quartz", BoolMode::And),
    // Required with optional terms.
    ("+every music", BoolMode::Or),
    ("+triad +patch lynx", BoolMode::Or),
    ("+most common band york", BoolMode::Or),
    ("+every +most triad onyx", BoolMode::Or),
    // Negation.
    ("every -triad", BoolMode::Or),
    ("most -common", BoolMode::Or),
    ("+triad -patch music", BoolMode::Or),
    ("every -most", BoolMode::And),
    // Phrases, over lists of hundreds to thousands of documents.
    ("\"new york city\"", BoolMode::Or),
    ("\"new york\"", BoolMode::Or),
    ("\"every new\"", BoolMode::Or),
    ("\"every triad\"", BoolMode::Or),
    ("\"stone stone triad\"", BoolMode::Or),
    ("\"every most\" music", BoolMode::Or),
    ("+\"new york\" -triad", BoolMode::Or),
    ("common -\"new york city\"", BoolMode::Or),
    ("\"york city\" every most", BoolMode::And),
];

/// Term lists for the unranked counts, each under both operators.
const COUNT_TERMS: [&[&str]; 6] = [
    &["every"],
    &["every", "most"],
    &["triad", "patch"],
    &["common", "music", "band"],
    &["most", "lynx", "quartz"],
    &["every", "most", "triad", "patch", "zephyr"],
];

/// Phrases, each a list of adjacent words.
type Phrases = &'static [&'static [&'static str]];

/// Phrase counts: `(positive phrases, negated terms, negated phrases)`.
const PHRASE_COUNTS: [(Phrases, &[&str], Phrases); 5] = [
    (&[&["new", "york", "city"]], &[], &[]),
    (&[&["new", "york"]], &["triad"], &[]),
    (&[&["every", "new"], &["york", "city"]], &[], &[]),
    (&[&["every", "triad"]], &[], &[&["new", "york"]]),
    (&[&["stone", "stone"]], &["patch"], &[]),
];

/// Documents in the corpus: enough for several terms to span dozens of
/// posting blocks.
const N_DOCS: u64 = 6_000;

/// Seed of the generator that draws filler words and placements.
const SEED: u64 = 0x9E37_79B9_7F4A_7C15;

/// Filler words and their relative draw weights: `common` lands in most
/// documents, `quartz` in a few hundred.
const FILLER: [(&str, u64); 8] = [
    ("common", 16),
    ("new", 10),
    ("york", 7),
    ("music", 5),
    ("band", 4),
    ("album", 3),
    ("river", 2),
    ("quartz", 1),
];

/// Every document draws `FILLER_MIN` to `FILLER_MIN + FILLER_SPAN - 1`
/// filler words.
const FILLER_MIN: u64 = 3;
const FILLER_SPAN: u64 = 4;

/// One document in this many carries [`PHRASE`] at a random offset.
const PHRASE_EVERY: u64 = 9;
const PHRASE: [&str; 3] = ["new", "york", "city"];

/// `triad` sits in every third document: regular deltas that pack
/// narrower than presence bits. One in [`TRIAD_TRIPLE_EVERY`] holds it
/// three times, spread across the document.
const TRIAD_STRIDE: u64 = 3;
const TRIAD_TRIPLE_EVERY: u64 = 33;

/// One document in [`LONG_EVERY`] (at offset [`LONG_AT`], a `triad`
/// document) is padded with [`LONG_PAD`] copies of `stone` and then holds
/// `triad` once more: a wide position gap among narrow ones, and a tf far
/// above the rest.
const LONG_EVERY: u64 = 300;
const LONG_AT: u64 = 6;
const LONG_PAD: usize = 40;

/// `patch` steps [`PATCH_STRIDE`] documents at a time, with a jump of
/// [`PATCH_JUMP`] every [`PATCH_OUTLIER_EVERY`] postings: a few wide
/// deltas among narrow ones.
const PATCH_STRIDE: u64 = 3;
const PATCH_JUMP: u64 = 200;
const PATCH_OUTLIER_EVERY: u64 = 24;

/// Rare words, each in documents `i` with `i % modulus == residue`:
/// lists short enough for the short form.
const RARE: [(&str, u64, u64); 3] = [("lynx", 211, 0), ("onyx", 97, 5), ("zephyr", 50, 3)];

/// A word in exactly one document.
const SINGLETON: (&str, u64) = ("solo", 4_321);

/// A word in exactly two documents: a list small enough that its
/// positions are stored as plain varints.
const PAIR: (&str, [u64; 2]) = ("duo", [1_234, 5_678]);

/// `every` is in every document but one in [`EVERY_GAP`]: long stretches
/// of consecutive ids. It leads its document, except one time in
/// [`EVERY_TAIL_ONE_IN`] when it ends it instead.
const EVERY_GAP: u64 = 487;
const EVERY_TAIL_ONE_IN: u64 = 50;

/// `most` is missing from one document in [`MOST_MISS_ONE_IN`], at
/// random, and held twice by one in [`MOST_TWICE_ONE_IN`]: dense blocks
/// with holes, stored as presence bits.
const MOST_MISS_ONE_IN: u64 = 16;
const MOST_TWICE_ONE_IN: u64 = 10;

/// A small deterministic generator (xorshift64).
struct Rng(u64);

impl Rng {
    fn below(&mut self, n: u64) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0 % n
    }
}

/// The corpus, document `i` at index `i`.
fn corpus() -> Vec<String> {
    let mut patched = vec![false; N_DOCS as usize];
    let (mut d, mut placed) = (1u64, 0u64);
    while d < N_DOCS {
        patched[d as usize] = true;
        placed += 1;
        d += match placed % PATCH_OUTLIER_EVERY == 0 {
            true => PATCH_JUMP,
            false => PATCH_STRIDE,
        };
    }
    let total: u64 = FILLER.iter().map(|&(_, w)| w).sum();
    let mut rng = Rng(SEED);
    (0..N_DOCS)
        .map(|i| {
            let mut t: Vec<&str> = Vec::new();
            for _ in 0..FILLER_MIN + rng.below(FILLER_SPAN) {
                let mut r = rng.below(total);
                for &(word, weight) in &FILLER {
                    if r < weight {
                        t.push(word);
                        break;
                    }
                    r -= weight;
                }
            }
            if i % PHRASE_EVERY == 0 {
                let at = rng.below(t.len() as u64 + 1) as usize;
                t.splice(at..at, PHRASE);
            }
            if i % TRIAD_STRIDE == 0 {
                t.push("triad");
                if i % TRIAD_TRIPLE_EVERY == 0 {
                    t.insert(0, "triad");
                    t.insert(t.len() / 2, "triad");
                }
            }
            if i % LONG_EVERY == LONG_AT {
                t.extend(["stone"; LONG_PAD]);
                t.push("triad");
            }
            if patched[i as usize] {
                t.push("patch");
            }
            if let Some(&(word, _, _)) = RARE.iter().find(|&&(_, m, r)| i % m == r) {
                t.push(word);
            }
            if i == SINGLETON.1 {
                t.push(SINGLETON.0);
            }
            if PAIR.1.contains(&i) {
                t.push(PAIR.0);
            }
            if rng.below(MOST_MISS_ONE_IN) != 0 {
                t.push("most");
                if rng.below(MOST_TWICE_ONE_IN) == 0 {
                    t.insert(0, "most");
                }
            }
            if i % EVERY_GAP != 0 {
                match rng.below(EVERY_TAIL_ONE_IN) == 0 {
                    true => t.push("every"),
                    false => t.insert(0, "every"),
                }
            }
            t.join(" ")
        })
        .collect()
}

/// The FTS section's version, read from the section header the Parquet
/// footer points at.
fn fts_version(bytes: &[u8], reader: &SuperfileReader) -> u32 {
    let offset: usize = reader
        .parquet_metadata()
        .file_metadata()
        .key_value_metadata()
        .and_then(|kvs| kvs.iter().find(|e| e.key == kv::FTS_OFFSET))
        .and_then(|e| e.value.as_deref())
        .expect("an FTS offset in the footer")
        .parse()
        .expect("a numeric FTS offset");
    assert_eq!(&bytes[offset..offset + fts::MAGIC.len()], fts::MAGIC);
    let at = offset + fts::MAGIC.len();
    u32::from_le_bytes(bytes[at..at + 4].try_into().expect("four version bytes"))
}

/// The corpus written by the current writer, as the fixture's generator
/// wrote it.
fn build_current(docs: &[String]) -> Vec<u8> {
    let schema = Arc::new(Schema::new(vec![
        Field::new(ID_COLUMN, DataType::Decimal128(38, 0), false),
        Field::new(COLUMN, DataType::LargeUtf8, false),
    ]));
    let opts = BuilderOptions::new(
        schema.clone(),
        ID_COLUMN,
        vec![FtsConfig::new(COLUMN).positions(true)],
        vec![],
    );
    let mut b = SuperfileBuilder::new(opts).expect("new SuperfileBuilder");
    let ids = decimal128_ids(0..N_DOCS);
    let bodies = LargeStringArray::from(docs.iter().map(String::as_str).collect::<Vec<_>>());
    let batch = RecordBatch::try_new(schema, vec![Arc::new(ids), Arc::new(bodies)])
        .expect("build RecordBatch");
    b.add_batch(&batch, &[]).expect("add_batch");
    b.finish().expect("finish builder")
}

/// The fixture's stored text, in row order.
fn stored_text(reader: &SuperfileReader) -> Vec<String> {
    let parquet = reader
        .parquet_bytes()
        .expect("eager open retains parquet bytes")
        .clone();
    let rows = ParquetRecordBatchReaderBuilder::try_new(parquet)
        .expect("parquet reader builder")
        .build()
        .expect("parquet reader");
    let mut out = Vec::new();
    for batch in rows {
        let batch = batch.expect("decode batch");
        let text = batch
            .column_by_name(COLUMN)
            .expect("text column")
            .as_any()
            .downcast_ref::<LargeStringArray>()
            .expect("large utf8 text");
        out.extend((0..text.len()).map(|i| text.value(i).to_string()));
    }
    out
}

/// Ranked hits as `(row, score bits)`, so equality is bit-for-bit.
async fn hits(reader: &SuperfileReader, query: &str, k: usize, mode: BoolMode) -> Vec<(u32, u32)> {
    reader
        .bm25_hits_async(COLUMN, query, k, mode)
        .await
        .expect("BM25 search")
        .into_iter()
        .map(|(row, score)| (row.get(), score.to_bits()))
        .collect()
}

/// Owned adjacent phrases from word lists.
fn phrases(lists: &[&[&str]]) -> Vec<Phrase<String>> {
    lists
        .iter()
        .map(|words| Phrase::adjacent(words.iter().map(|w| w.to_string()).collect()))
        .collect()
}

/// A phrase-count case in the query syntax, for the brute-force oracle.
fn phrase_count_query(
    positives: &[&[&str]],
    neg_terms: &[&str],
    neg_phrases: &[&[&str]],
) -> String {
    let quoted = |words: &&[&str]| format!("\"{}\"", words.join(" "));
    let mut parts: Vec<String> = positives
        .iter()
        .map(|p| format!("+{}", quoted(p)))
        .collect();
    parts.extend(neg_terms.iter().map(|t| format!("-{t}")));
    parts.extend(neg_phrases.iter().map(|p| format!("-{}", quoted(p))));
    parts.join(" ")
}

/// The fixture, its FTS section checked to be version 9 and its text the
/// corpus.
fn open_fixture(docs: &[String]) -> SuperfileReader {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(FIXTURE);
    let bytes = Bytes::from(std::fs::read(&path).expect("read fixture"));
    let reader = SuperfileReader::open(bytes.clone()).expect("open fixture");
    assert_eq!(
        fts_version(&bytes, &reader),
        fts::VERSION_V9,
        "the fixture must stay a version-9 file"
    );
    assert_eq!(reader.n_docs(), N_DOCS);
    assert_eq!(
        stored_text(&reader),
        docs,
        "the fixture holds the corpus this file generates"
    );
    reader
}

/// A file of the current version, opened.
fn open_current(bytes: Vec<u8>) -> SuperfileReader {
    let bytes = Bytes::from(bytes);
    let reader = SuperfileReader::open(bytes.clone()).expect("open superfile");
    assert_eq!(fts_version(&bytes, &reader), fts::VERSION_CURRENT);
    reader
}

/// Assert `candidate` answers every query as `current` does, and both as
/// the brute-force oracle does.
///
/// With `same_order`, ranked hits must be identical, rows and score bits,
/// ties included. Without it, `candidate` orders its documents its own
/// way (a merge's output does), and a top-k breaks equal scores by that
/// order, so it may name other rows among tied ones: its scores must then
/// be the same sequence, each the score `current` gives that row.
async fn assert_answers_as_current(
    candidate: &SuperfileReader,
    current: &SuperfileReader,
    docs: &[String],
    same_order: bool,
) {
    let refs: Vec<(u64, &str)> = docs
        .iter()
        .enumerate()
        .map(|(i, t)| (i as u64, t.as_str()))
        .collect();
    let tok = default_tokenizer();
    let oracle = BruteForceBm25::index(&refs, tok.as_ref());

    for word in WORDS {
        let want = docs
            .iter()
            .filter(|t| t.split(' ').any(|w| w == word))
            .count() as u64;
        for reader in [candidate, current] {
            let (df, _) = reader.term_df(COLUMN, word).await.expect("term df");
            assert_eq!(df, want, "df of {word}");
        }
    }

    for (query, mode) in QUERIES {
        let want: HashSet<u32> = oracle
            .top_k_query(query, mode, tok.as_ref(), N_DOCS as usize)
            .into_iter()
            .map(|(doc, _)| doc as u32)
            .collect();
        let every_hit: HashMap<u32, u32> = hits(current, query, N_DOCS as usize, mode)
            .await
            .into_iter()
            .collect();
        let got_rows: HashSet<u32> = every_hit.keys().copied().collect();
        assert_eq!(got_rows, want, "{query:?} ({mode:?}): match set");
        for k in KS {
            let label = format!("{query:?} ({mode:?}) k={k}");
            let reference = hits(current, query, k, mode).await;
            assert_eq!(reference.len(), k.min(want.len()), "{label}: hit count");
            let got = hits(candidate, query, k, mode).await;
            if same_order {
                assert_eq!(got, reference, "{label}: hits");
                continue;
            }
            let scores = |h: &[(u32, u32)]| h.iter().map(|&(_, s)| s).collect::<Vec<_>>();
            assert_eq!(scores(&got), scores(&reference), "{label}: scores");
            for (row, score) in got {
                assert_eq!(every_hit.get(&row), Some(&score), "{label}: row {row}");
            }
        }
    }

    for terms in COUNT_TERMS {
        for mode in [BoolMode::And, BoolMode::Or] {
            let label = format!("{terms:?} ({mode:?})");
            let want = oracle
                .top_k_query(&terms.join(" "), mode, tok.as_ref(), N_DOCS as usize)
                .len() as u64;
            let (rows, _) = current
                .token_match(COLUMN, terms, mode)
                .await
                .expect("token match");
            assert_eq!(rows.len() as u64, want, "{label}: current rows");
            let (got, _) = candidate
                .token_match(COLUMN, terms, mode)
                .await
                .expect("token match");
            assert_eq!(got, rows, "{label}: rows");
            for reader in [candidate, current] {
                let (count, _) = reader
                    .token_match_count(COLUMN, terms, mode)
                    .await
                    .expect("token match count");
                assert_eq!(count, want, "{label}: count");
            }
        }
    }

    for (positives, neg_terms, neg_phrases) in PHRASE_COUNTS {
        let query = phrase_count_query(positives, neg_terms, neg_phrases);
        let want = oracle
            .top_k_query(&query, BoolMode::Or, tok.as_ref(), N_DOCS as usize)
            .len() as u64;
        assert!(want > 0, "{query}: the corpus holds matches");
        let (positives, neg_phrases) = (phrases(positives), phrases(neg_phrases));
        for reader in [candidate, current] {
            let (count, _) = reader
                .atoms_match_count(
                    COLUMN,
                    &[],
                    &positives,
                    BoolMode::And,
                    neg_terms,
                    &neg_phrases,
                )
                .await
                .expect("atoms match count");
            assert_eq!(count, want, "{query}: count");
        }
    }
}

#[tokio::test]
async fn a_version_9_superfile_answers_as_the_current_writer_does() {
    let docs = corpus();
    let fixture = open_fixture(&docs);
    let current = open_current(build_current(&docs));
    assert_answers_as_current(&fixture, &current, &docs, true).await;
}

#[tokio::test]
async fn a_merge_of_a_version_9_superfile_answers_as_the_current_writer_does() {
    // The merge reads every legacy block and position group through its
    // postings walk and writes them in the current version.
    let docs = corpus();
    let fixture = Arc::new(open_fixture(&docs));
    let (merged, _) = SuperfileBuilder::build_from_readers_fts_merge(&[(fixture, None)])
        .expect("merge the fixture alone");
    let merged = open_current(merged);
    let current = open_current(build_current(&docs));
    assert_answers_as_current(&merged, &current, &docs, false).await;
}
